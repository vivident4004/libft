int	ft_atoi(const char *nptr)
{
	int	segno;
	int	n;

	segno = 1;
	n = 0;
	while ((*nptr >= '\t' && *nptr <= '\r') || *nptr == ' ')
		nptr++;
	if (*nptr == '-' || *nptr == '+')
	{
		if (*nptr == '-')
			segno = -1;
		nptr++;
	}
	while (*nptr >= '0' && *nptr <= '9')
		n = n * 10 + (*nptr++ - '0');
	return (n * segno);
}
